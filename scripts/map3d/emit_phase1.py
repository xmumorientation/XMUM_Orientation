"""Write src/components/map3d/campusData.ts (phase 1 of the true-scale map) from campus.json.

Usage: python3 -I scripts/map3d/emit_phase1.py [campus.json] [campusData.ts]

Phase 1 is the key places only: A1-A5, B1, the LakeFront Cafe dome, the lake,
the lake park with its footpaths and footbridge, and the lawns round the
Tan Kah Kee statue. Roads, dorms and trees come later (phase 2).
Coordinates stay in metres east / north of the Track & Field GPS point.
"""
import json, math, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(HERE, "campus.json")
DST = sys.argv[2] if len(sys.argv) > 2 else os.path.join(HERE, "../../src/components/map3d/campusData.ts")

# The lake park, the A-row and the statue lawns (metres east / north).
ZONE = (-540, -60, -130, 370)

d = json.load(open(SRC))
F = {f["id"]: f for f in d["features"]}
by_label = {f.get("label"): f for f in d["features"] if f.get("label")}


def in_zone(f):
    e, n = f["centroid"]
    return ZONE[0] < e < ZONE[1] and ZONE[2] < n < ZONE[3] and f.get("inCampus")


def ring(f):
    return f["geometry"]["coordinates"][0]


def fmt_pts(pts):
    return "[" + ", ".join(f"[{p[0]:.1f}, {p[1]:.1f}]" for p in pts) + "]"


def rect(f):
    r = f["rect"]
    return {"e": r["cE"], "n": r["cN"], "length": r["length"], "width": r["width"], "bearing": r["bearing"]}


def inside(pt, poly):
    x, y = pt
    hit = False
    for i in range(len(poly)):
        (x1, y1), (x2, y2) = poly[i], poly[i - 1]
        if (y1 > y) != (y2 > y) and x < (x2 - x1) * (y - y1) / (y2 - y1) + x1:
            hit = not hit
    return hit


def edge_dist(pt, poly):
    best = math.inf
    for i in range(len(poly)):
        (ax, ay), (bx, by) = poly[i - 1], poly[i]
        dx, dy = bx - ax, by - ay
        t = max(0, min(1, ((pt[0] - ax) * dx + (pt[1] - ay) * dy) / (dx * dx + dy * dy or 1)))
        best = min(best, math.hypot(pt[0] - ax - dx * t, pt[1] - ay - dy * t))
    return best


buildings = {name: rect(by_label[name]) for name in ("A1", "A2", "A3", "A4", "A5", "B1")}
buildings["LakeFront Cafe"] = rect(F["way/1145060153"])

lake = ring(F["way/544590729"])
park = ring(F["way/616520161"])
grass = [ring(f) for f in d["features"] if f["kind"] == "landuse" and f.get("tags", {}).get("landuse") == "grass" and in_zone(f)]
bridge = F["way/616517094"]["geometry"]["coordinates"]
# Paths OSM has visibly off the imagery, traced again by hand in geo.ts (TRACED_PATHS_M): the walk along the east
# edge of the lawn east of A5, which OSM draws about 11 m east of it, in the trees.
RETRACED = {"way/1422330769"}
paths = [
    f["geometry"]["coordinates"]
    for f in d["features"]
    if f["kind"] == "path"
    and f["id"] != "way/616517094"
    and f["id"] not in RETRACED
    and f["geometry"]["type"] == "LineString"
    and in_zone(f)
]

# The widest open water away from the footbridge and the dome: room for the duck.
es = [p[0] for p in lake]
ns = [p[1] for p in lake]
dome = (buildings["LakeFront Cafe"]["e"], buildings["LakeFront Cafe"]["n"])
best = (0, 0, 0)
e = min(es)
while e < max(es):
    n = min(ns)
    while n < max(ns):
        if inside((e, n), lake):
            r = min(edge_dist((e, n), lake), edge_dist((e, n), bridge) - 6, math.hypot(e - dome[0], n - dome[1]) - 25)
            if r > best[2]:
                best = (e, n, r)
        n += 2
    e += 2

out = [
    "// Generated by scripts/map3d/emit_phase1.py from scripts/map3d/campus.json. Do not edit by hand.",
    "// Data © OpenStreetMap contributors (ODbL). Metres east (e) / north (n) of the Track & Field GPS point.",
    "",
    "export type EN = [number, number];",
    "",
    "/** Footprint as a rectangle: centre, long side, short side, bearing of the long side (degrees clockwise from north). */",
    "export type RectM = { e: number; n: number; length: number; width: number; bearing: number };",
    "",
    "export const BUILDINGS_M: Record<string, RectM> = {",
]
for name, r in buildings.items():
    out.append(f'  "{name}": {{ e: {r["e"]}, n: {r["n"]}, length: {r["length"]}, width: {r["width"]}, bearing: {r["bearing"]} }},')
out += [
    "};",
    "",
    f"export const LAKE_M: EN[] = {fmt_pts(lake)};",
    "",
    "/** The lake park round the lake (OSM leisure=park). */",
    f"export const PARK_M: EN[] = {fmt_pts(park)};",
    "",
    "/** Lawns round the statue and the A-row (OSM landuse=grass). */",
    "export const GRASS_M: EN[][] = [",
    *[f"  {fmt_pts(g)}," for g in grass],
    "];",
    "",
    "/** Footpaths in the park and in front of the A-row (OSM highway=footway and steps). */",
    "export const FOOTPATHS_M: EN[][] = [",
    *[f"  {fmt_pts(p)}," for p in paths],
    "];",
    "",
    "/** The wooden footbridge across the lake. */",
    f"export const FOOTBRIDGE_M: [EN, EN] = {fmt_pts(bridge)};",
    "",
    "/** Open water with room for the duck: centre and clear radius. */",
    f"export const DUCK_M = {{ e: {best[0]:.1f}, n: {best[1]:.1f}, r: {best[2]:.1f} }};",
    "",
]
open(DST, "w").write("\n".join(out))
print(f"wrote {DST}: {len(grass)} lawns, {len(paths)} paths, duck at {best[0]:.0f},{best[1]:.0f} r={best[2]:.0f} m")
